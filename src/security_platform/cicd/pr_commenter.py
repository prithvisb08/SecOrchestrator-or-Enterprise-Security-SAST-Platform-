import json
import urllib.request

from security_platform.cicd.gate import SecurityGateResult
from security_platform.models.finding import Finding
from security_platform.risk.models import RiskAssessment


class PRCommenter:
    """Formats and posts scan summaries directly to GitHub Pull Requests."""

    def format_markdown_comment(
        self,
        risk: RiskAssessment,
        findings: list[Finding],
        gate: SecurityGateResult
    ) -> str:
        status_badge = "✅ **PASSED**" if gate.passed else "❌ **FAILED**"

        md = "## 🛡️ Security Platform Scan Results\n\n"
        md += f"**Status:** {status_badge}\n"
        md += f"**Overall Risk Score:** `{risk.overall_risk_score} / 10.0` ({risk.risk_level.value})\n"
        md += f"**Total Findings:** `{len(findings)}` \n\n"

        if not gate.passed:
            md += "### ⚠️ Gate Failure Reasons\n"
            for reason in gate.reasons:
                md += f"- {reason}\n"
            md += "\n"

        if findings:
            md += "### 🔍 Top Findings\n"
            md += "| Severity | Rule ID | Title | File & Line |\n"
            md += "| :--- | :--- | :--- | :--- |\n"

            # Show up to 10 findings in the summary table
            for f in findings[:10]:
                md += f"| **{f.severity.value}** | `{f.rule_id}` | {f.title} | `{f.location.file_path}:{f.location.start_line}` |\n"

            if len(findings) > 10:
                md += f"\n*...and {len(findings) - 10} more finding(s). Check full SARIF output for details.*\n"

        md += "\n---\n*Automated scan generated by Security Orchestrator Engine.*"
        return md

    def post_comment(self, repo: str, pr_number: int, token: str, markdown_body: str) -> bool:
        """Posts a markdown summary to the GitHub Pull Request via standard API."""
        url = f"https://api.github.com/repos/{repo}/issues/{pr_number}/comments"
        headers = {
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github.v3+json",
            "Content-Type": "application/json"
        }

        data = json.dumps({"body": markdown_body}).encode("utf-8")
        req = urllib.request.Request(url, data=data, headers=headers, method="POST")

        try:
            with urllib.request.urlopen(req) as response:
                return response.status in (200, 201)
        except Exception as e:
            print(f"Failed to post PR comment: {e}")
            return False
