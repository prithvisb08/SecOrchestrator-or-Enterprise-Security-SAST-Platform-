import json
import urllib.request

from security_platform.remediation.engine import RemediationResult


class AutoPRCreator:
    """Creates a remediation pull request on GitHub with automated security patches."""

    def format_pr_body(self, results: list[RemediationResult]) -> str:
        total_fixes = sum(r.fixes_applied for r in results)

        body = "## 🤖 Automated Security Remediation\n\n"
        body += f"This automated PR applies **{total_fixes} security fix(es)** generated by the Security Engine.\n\n"
        body += "### Modified Files:\n"

        for res in results:
            body += f"- `{res.file_path}` ({res.fixes_applied} fix(es) applied)\n"

        body += "\n---\n*Please review changes and test suite before merging.*"
        return body

    def create_pull_request(
        self,
        repo: str,
        token: str,
        head_branch: str,
        base_branch: str,
        title: str,
        body: str
    ) -> bool:
        url = f"https://api.github.com/repos/{repo}/pulls"
        headers = {
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github.v3+json",
            "Content-Type": "application/json"
        }

        payload = {
            "title": title,
            "head": head_branch,
            "base": base_branch,
            "body": body
        }

        req = urllib.request.Request(url, data=json.dumps(payload).encode("utf-8"), headers=headers, method="POST")

        try:
            with urllib.request.urlopen(req) as response:
                return response.status in (200, 201)
        except Exception as e:
            print(f"Failed to create PR: {e}")
            return False
